/**
 * Destructible homing micro-missile fired by Tetsuyuki's dorsal rocket pods.
 * Tracks target player position with 2.2 rad/s max steering rate.
 * Has HP = 1, so a single player bullet destroys it in mid-air.
 */
export class TetsuyukiHomingMissile implements GameEntity {
  public id: string;
  public type: string = 'HOMING_MISSILE';
  public position: Vector2D;
  public velocity: Vector2D;
  public bounds: AABB;
  public isAlive: boolean = true;
  public health: number = 1;
  public headingAngle: number;
  public readonly speed: number = 175;
  public readonly maxSteerRate: number = 2.2; // 2.2 rad/s
  public blastRadius: number = 32;
  public damage: number = 2;
  private lifetime: number = 4.5;
  private targetPlayer: TargetPlayer | null = null;

  constructor(
    id: string,
    startPos: Vector2D,
    initialAngle: number = Math.PI,
    target: TargetPlayer | null = null
  ) {
    this.id = id;
    this.position = { x: startPos.x, y: startPos.y };
    this.headingAngle = initialAngle;
    this.velocity = {
      x: Math.cos(initialAngle) * this.speed,
      y: Math.sin(initialAngle) * this.speed,
    };
    this.bounds = createAABB(this.position.x, this.position.y, 10, 6);
    this.targetPlayer = target;
  }

  setTarget(target: TargetPlayer | null): void {
    this.targetPlayer = target;
  }

  takeDamage(amount: number): void {
    this.health -= amount;
    if (this.health <= 0) {
      this.health = 0;
      this.isAlive = false;
    }
  }

  update(dt: number, engine?: GameEngine): void {
    if (!this.isAlive) {
      if (engine) engine.removeEntity(this.id);
      return;
    }

    // Steering towards player target
    if (this.targetPlayer && this.targetPlayer.isAlive !== false) {
      const targetAngle = Math.atan2(
        this.targetPlayer.position.y - this.position.y,
        this.targetPlayer.position.x - this.position.x
      );

      let deltaAngle = Math.atan2(
        Math.sin(targetAngle - this.headingAngle),
        Math.cos(targetAngle - this.headingAngle)
      );

      const maxStep = this.maxSteerRate * dt;
      deltaAngle = Math.max(-maxStep, Math.min(maxStep, deltaAngle));
      this.headingAngle += deltaAngle;
    }

    this.velocity.x = Math.cos(this.headingAngle) * this.speed;
    this.velocity.y = Math.sin(this.headingAngle) * this.speed;

    this.position.x += this.velocity.x * dt;
    this.position.y += this.velocity.y * dt;
    this.bounds.x = this.position.x;
    this.bounds.y = this.position.y;

    this.lifetime -= dt;
    if (this.lifetime <= 0) {
      this.detonate(engine);
    }
  }

  detonate(engine?: GameEngine): void {
    if (!this.isAlive) return;
    this.isAlive = false;

    if (engine) {
      engine.eventBus.emit('explosion_spawned', {
        position: { x: this.position.x, y: this.position.y },
        radius: this.blastRadius,
        damage: this.damage,
      });
      engine.removeEntity(this.id);
    }
  }
}

/**
 * Traveling ground shockwave generated by Tetsuyuki's emergency thrusters.
 */
export class TetsuyukiShockwave implements GameEntity {
  public id: string;
  public type: string = 'THRUSTER_SHOCKWAVE';
  public position: Vector2D;
  public velocity: Vector2D;
  public bounds: AABB;
  public isAlive: boolean = true;
  public damage: number = 2;
  private lifetime: number = 2.8;

  constructor(id: string, startPos: Vector2D, speedX: number = -180) {
    this.id = id;
    this.position = { x: startPos.x, y: startPos.y };
    this.velocity = { x: speedX, y: 0 };
    this.bounds = createAABB(this.position.x, this.position.y, 28, 20);
  }

  update(dt: number, engine?: GameEngine): void {
    if (!this.isAlive) return;
    this.position.x += this.velocity.x * dt;
    this.bounds.x = this.position.x;

    this.lifetime -= dt;
    if (this.lifetime <= 0) {
      this.isAlive = false;
      if (engine) engine.removeEntity(this.id);
    }
  }
}

